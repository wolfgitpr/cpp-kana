#!/usr/bin/env python3
"""Writes ``csharp/CppKana2/BuildInfo.g.cs``: the native library's file name and the package version.

Why generated: ``DllImport`` needs a compile-time constant, so the loader cannot read a file at run time
the way the Python shell does. Baking the name in means the name has to come from somewhere real -- the
library that was actually built -- instead of a guess that only works on the machine that wrote it.

The version comes from the root ``CMakeLists.txt`` (the single authority). A missing native library is a
hard error here, not a warning: a package built without one installs and then fails to load.

    python csharp/tools/emit_build_info.py --native python/cpp_kana2/_native/libcpp-kana2.dll
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "csharp" / "CppKana2" / "BuildInfo.g.cs"
VERSION_PROPS = ROOT / "csharp" / "CppKana2" / "version.props"
LIBRARY_SUFFIXES = (".dll", ".so", ".dylib")


def project_version() -> str:
    text = (ROOT / "CMakeLists.txt").read_text(encoding="utf-8")
    match = re.search(r"project\(\s*cpp-kana2\s+VERSION\s+([0-9.]+)", text)
    if not match:
        raise SystemExit("could not read the version from CMakeLists.txt's project(... VERSION ...)")
    return match.group(1)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--native", type=Path, required=True, help="the built native library")
    args = parser.parse_args()

    library = args.native
    if not library.is_file() or library.suffix not in LIBRARY_SUFFIXES:
        raise SystemExit(f"{library} is not a built native library ({', '.join(LIBRARY_SUFFIXES)})")

    version = project_version()
    OUTPUT.write_text(
        "// Generated by csharp/tools/emit_build_info.py. Do not edit, and do not track.\n"
        "namespace CppKana2\n"
        "{\n"
        "    internal static class BuildInfo\n"
        "    {\n"
        f'        internal const string NativeLibraryName = "{library.name}";\n'
        f'        internal const string PackageVersion = "{version}";\n'
        "    }\n"
        "}\n",
        encoding="utf-8",
        newline="\n",
    )
    # The assembly/package version, so the managed side reports the same number as the native side. Written
    # as an imported .props rather than duplicated in the csproj: the version has one authority
    # (CMakeLists.txt) and this is a projection of it.
    VERSION_PROPS.write_text(
        "<Project>\n"
        "  <PropertyGroup>\n"
        f"    <Version>{version}</Version>\n"
        f"    <AssemblyVersion>{version}</AssemblyVersion>\n"
        f"    <FileVersion>{version}</FileVersion>\n"
        "  </PropertyGroup>\n"
        "</Project>\n",
        encoding="utf-8",
        newline="\n",
    )
    print(
        f"wrote {OUTPUT.relative_to(ROOT)} and {VERSION_PROPS.relative_to(ROOT)} "
        f"(native {library.name}, version {version})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
