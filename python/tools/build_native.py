#!/usr/bin/env python3
"""Stages what the Python package needs: the native library, ``_version.py``, and ``_native/name.txt``.

Order matters and is enforced here: the version file is written FIRST (so ``import cpp_kana2`` works even
if the build then fails, and so a wheel can never be built with a stale version), then the library is
built or copied, then its real file name is recorded.

Why record the name instead of hard-coding it: it differs per platform and per build layout
(``cpp-kana2.dll``, ``libcpp-kana2.dll``, ``libcpp-kana2.so``, ``libcpp-kana2.dylib``, with or without a
version suffix). ``_native.py`` reads that file; a name it cannot find is an error, not a fallback to some
other library of the same base name.

    python python/tools/build_native.py                       # configure + build + stage
    python python/tools/build_native.py --native-dir <dir>    # stage an existing build
"""

from __future__ import annotations

import argparse
import re
import shutil
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / "python" / "cpp_kana2"
NATIVE_DIR = PACKAGE / "_native"
LIBRARY_SUFFIXES = (".dll", ".so", ".dylib")
LIBRARY_STEM = "cpp-kana2"


def project_version() -> str:
    text = (ROOT / "CMakeLists.txt").read_text(encoding="utf-8")
    match = re.search(r"project\(\s*cpp-kana2\s+VERSION\s+([0-9.]+)", text)
    if not match:
        raise SystemExit("could not read the version from CMakeLists.txt's project(... VERSION ...)")
    return match.group(1)


def write_version(version: str) -> None:
    # A plain assignment, not a literal inside the code: tools/check_version_tokens.py (P7) compares this
    # projection with the CMake one, and a comment here would be one more place to keep in step.
    target = PACKAGE / "_version.py"
    target.write_text(
        f'"""Generated by python/tools/build_native.py from CMakeLists.txt. Do not edit."""\n'
        f'__version__ = "{version}"\n',
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {target.relative_to(ROOT)} ({version})")


def find_library(directory: Path) -> Path:
    candidates = [
        entry
        for entry in sorted(directory.iterdir())
        if entry.is_file() and entry.suffix in LIBRARY_SUFFIXES and LIBRARY_STEM in entry.name
    ]
    if not candidates:
        raise SystemExit(f"no *{LIBRARY_STEM}*.dll|.so|.dylib in {directory}")
    # Prefer the shortest name: libcpp-kana2.so over libcpp-kana2.so.2, which is a symlink to the same file.
    candidates.sort(key=lambda path: (len(path.name), path.name))
    return candidates[0]


def build(build_dir: Path, config: str) -> Path:
    configure = [
        "cmake",
        "-S",
        str(ROOT),
        "-B",
        str(build_dir),
        "-G",
        # Ninja by default, but overridable: a manylinux image can be missing the ninja binary while its make
        # works, and forcing a generator there turns a missing tool into a failed release. MEASURED on release
        # runs 41170998959..41171417852.
        os.environ.get("CPP_KANA2_CMAKE_GENERATOR", "Ninja"),
        f"-DCMAKE_BUILD_TYPE={config}",
        "-DBUILD_SHARED_LIBS=ON",
        "-DCPP_KANA2_BUILD_TESTS=OFF",
        "-DCPP_KANA2_INSTALL=OFF",
    ]
    # MEASURED: a MinGW-built libcpp-kana2.dll depends on libgcc_s_seh-1.dll and libstdc++-6.dll, and
    # ctypes then fails with "could not find module ... (or one of its dependencies)" on a machine whose
    # PATH has no MinGW -- which is every user's machine. Linking the runtime statically leaves only
    # OS-provided UCRT/KERNEL32 imports, so the staged file is shippable as-is. (objdump -p confirms it.)
    if sys.platform == "win32":
        configure.append("-DCMAKE_SHARED_LINKER_FLAGS=-static -static-libgcc -static-libstdc++")
    print("+ " + " ".join(configure))
    subprocess.run(configure, check=True)
    build_command = ["cmake", "--build", str(build_dir)]
    print("+ " + " ".join(build_command))
    subprocess.run(build_command, check=True)
    for candidate in (build_dir / "bin", build_dir / "lib"):
        if candidate.is_dir() and any(entry.suffix in LIBRARY_SUFFIXES for entry in candidate.iterdir()):
            return candidate
    return build_dir


def stage(directory: Path) -> None:
    library = find_library(directory)
    NATIVE_DIR.mkdir(parents=True, exist_ok=True)
    for stale in NATIVE_DIR.glob(f"*{LIBRARY_STEM}*"):
        stale.unlink()
    target = NATIVE_DIR / library.name
    shutil.copy2(library, target)
    (NATIVE_DIR / "name.txt").write_text(library.name + "\n", encoding="utf-8", newline="\n")
    print(f"staged {library.name} -> {target.relative_to(ROOT)}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--native-dir", type=Path, help="directory holding an already-built library")
    parser.add_argument("--build-dir", type=Path, default=ROOT / ".tmp" / "py-native")
    parser.add_argument("--config", default="Release")
    args = parser.parse_args()

    write_version(project_version())

    if args.native_dir is not None:
        stage(args.native_dir)
    else:
        stage(build(args.build_dir, args.config))

    # Prove what was staged actually loads and answers, rather than only that a file exists.
    sys.path.insert(0, str(ROOT / "python"))
    import cpp_kana2  # noqa: PLC0415 - imported after staging on purpose

    conversion = cpp_kana2.kana_to_romaji("きって")
    print(f"smoke: native version {cpp_kana2.version()}, きって -> {conversion.rendered!r}")
    if conversion.rendered.replace(" ", "") != "kitte":
        raise SystemExit(f"staged library answered {conversion.rendered!r}, expected 'kitte'")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
