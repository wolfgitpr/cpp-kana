"""cpp-kana2 for Python: a thin, honest shell over the C ABI.

Design rules, all of which exist because a binding that invents behaviour is worse than no binding:

* One-to-one with the C surface. ``kana_to_romaji``, ``romaji_to_kana``, ``convert_script``, ``version`` and
  ``code_text`` are the whole API; the option objects mirror the option structs field for field.
* Failures raise, because that is what a Python caller expects -- and each status code maps to its own
  exception class (see ``_errors``). The detail text always comes from the library, never from here.
* Every native allocation is released in a ``finally``. The conversion is copied into plain Python objects
  before the native one is freed, so a returned object never points into freed memory.
* No hidden retries, no normalisation, no silent replacement characters: what the library says is what you
  get.
"""

