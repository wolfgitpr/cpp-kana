class MoraKind(IntEnum):
    SYLLABLE = _ffi.MORA_SYLLABLE
    SOKUON = _ffi.MORA_SOKUON
    HATSUON = _ffi.MORA_HATSUON
    LONG_VOWEL = _ffi.MORA_LONG_VOWEL
    OTHER = _ffi.MORA_OTHER
    ARCHAIC = _ffi.MORA_ARCHAIC
    ROMAJI = _ffi.MORA_ROMAJI


class Script(IntEnum):
    HIRAGANA = _ffi.SCRIPT_HIRAGANA
    KATAKANA = _ffi.SCRIPT_KATAKANA
    AS_IS = _ffi.SCRIPT_AS_IS


@dataclass(frozen=True)
class Mora:
    """One unit of a conversion, copied out of the native structure."""

    text: str
    rendered: str
    kind: MoraKind
    code: int

    @property
    def ok(self) -> bool:
        return self.code == _ffi.OK


@dataclass(frozen=True)
class Conversion:
    """The whole result: the rendered string plus the per-unit breakdown."""

    text: str
    rendered: str
    moras: Tuple[Mora, ...]
    ok: bool

    def __str__(self) -> str:
        return self.rendered

    def __len__(self) -> int:
        return len(self.moras)


_SCRIPT_NAMES = {"hiragana": Script.HIRAGANA, "katakana": Script.KATAKANA, "as_is": Script.AS_IS}
_SOKUON_NAMES = {"geminate": _ffi.SOKUON_GEMINATE, "drop": _ffi.SOKUON_DROP}
_HATSUON_NAMES = {"apostrophe": _ffi.HATSUON_APOSTROPHE, "plain": _ffi.HATSUON_PLAIN}
_LONG_VOWEL_NAMES = {"repeat": _ffi.LONG_VOWEL_REPEAT, "drop": _ffi.LONG_VOWEL_DROP, "dash": _ffi.LONG_VOWEL_KATAKANA_DASH}
_CASE_NAMES = {"lower": _ffi.CASE_LOWER, "upper": _ffi.CASE_UPPER, "capitalize": _ffi.CASE_CAPITALIZE}
_SEPARATOR_NAMES = {"space": _ffi.SEPARATOR_SPACE, "none": _ffi.SEPARATOR_NONE}
_UNKNOWN_NAMES = {"keep": _ffi.UNKNOWN_KEEP, "ignore": _ffi.UNKNOWN_IGNORE, "fail": _ffi.UNKNOWN_FAIL}


def _lookup(table: dict, value, what: str) -> int:
    if isinstance(value, int):
        return int(value)
    try:
        return table[value]
    except (KeyError, TypeError):
        raise InvalidArgumentError(
            _ffi.ERR_INVALID_ARGUMENT, f"{what}={value!r} is not one of {sorted(table)}"
        ) from None


@dataclass(frozen=True)
class RomajiOptions:
    """Mirrors ``cppk2_romaji_options``. Defaults are the library's own defaults."""

    sokuon: str = "geminate"
    hatsuon: str = "apostrophe"
    long_vowel: str = "repeat"
    case: str = "lower"
    separator: str = "none"
    unknown: str = "keep"

    def _to_struct(self) -> _ffi.RomajiOptionsStruct:
        struct = _ffi.RomajiOptionsStruct()
        struct.struct_size = ctypes.sizeof(_ffi.RomajiOptionsStruct)
        status = _library.cppk2_romaji_options_init(ctypes.byref(struct), struct.struct_size)
        _errors.raise_for_status(status)
        struct.sokuon = _lookup(_SOKUON_NAMES, self.sokuon, "sokuon")
        struct.hatsuon = _lookup(_HATSUON_NAMES, self.hatsuon, "hatsuon")
        struct.long_vowel = _lookup(_LONG_VOWEL_NAMES, self.long_vowel, "long_vowel")
        struct.letter_case = _lookup(_CASE_NAMES, self.case, "case")
        struct.separator = _lookup(_SEPARATOR_NAMES, self.separator, "separator")
        struct.unknown = _lookup(_UNKNOWN_NAMES, self.unknown, "unknown")
        return struct


@dataclass(frozen=True)
class KanaOptions:
    """Mirrors ``cppk2_kana_options``."""

    script: str = "hiragana"
    unknown: str = "keep"

    def _to_struct(self) -> _ffi.KanaOptionsStruct:
        struct = _ffi.KanaOptionsStruct()
        struct.struct_size = ctypes.sizeof(_ffi.KanaOptionsStruct)
        status = _library.cppk2_kana_options_init(ctypes.byref(struct), struct.struct_size)
        _errors.raise_for_status(status)
        struct.script = int(_lookup(_SCRIPT_NAMES, self.script, "script"))
        struct.unknown = _lookup(_UNKNOWN_NAMES, self.unknown, "unknown")
        return struct


def _encode(text: str) -> bytes:
    if not isinstance(text, str):
        raise InvalidArgumentError(_ffi.ERR_INVALID_ARGUMENT, f"expected str, got {type(text).__name__}")
    if "\x00" in text:
        # The C ABI takes NUL-terminated strings; an embedded NUL would truncate silently.
        raise InvalidArgumentError(_ffi.ERR_INVALID_ARGUMENT, "text must not contain U+0000")
    return text.encode("utf-8")


def _convert(call) -> Conversion:
    out = ctypes.POINTER(_ffi.ConversionStruct)()
    error = _ffi.ErrorStruct()
    status = call(out, error)
    if status != _ffi.OK:
        detail = _ffi.take_detail(_library, error)
        _errors.raise_for_status(status, detail)
    try:
        native = out.contents
        moras = tuple(
            Mora(text=view.text, rendered=view.rendered, kind=MoraKind(view.kind), code=view.code)
            for view in _ffi.moras_of(native)
        )
        return Conversion(
            text=(native.text or b"").decode("utf-8", "replace"),
            rendered=(native.rendered or b"").decode("utf-8", "replace"),
            moras=moras,
            ok=bool(native.ok),
        )
    finally:
        _library.cppk2_conversion_free(out)


def kana_to_romaji(text: str, options: Optional[RomajiOptions] = None) -> Conversion:
    """Kana (hiragana, katakana, half-width, combining dakuten) -> Hepburn romaji."""
    data = _encode(text)
    if options is None:
        return _convert(lambda out, err: _library.cppk2_kana_to_romaji(data, None, out, err))
    struct = options._to_struct()
    return _convert(lambda out, err: _library.cppk2_kana_to_romaji(data, ctypes.byref(struct), out, err))


def romaji_to_kana(text: str, options: Optional[KanaOptions] = None) -> Conversion:
    """Hepburn romaji (plus Kunrei/IME aliases) -> kana."""
    data = _encode(text)
    if options is None:
        return _convert(lambda out, err: _library.cppk2_romaji_to_kana(data, None, out, err))
    struct = options._to_struct()
    return _convert(lambda out, err: _library.cppk2_romaji_to_kana(data, ctypes.byref(struct), out, err))


def convert_script(text: str, target: str = "hiragana", unknown: str = "keep") -> Conversion:
    """Hiragana <-> katakana, with half-width input normalised first."""
    data = _encode(text)
    script = int(_lookup(_SCRIPT_NAMES, target, "target"))
    unknown_code = _lookup(_UNKNOWN_NAMES, unknown, "unknown")
    return _convert(lambda out, err: _library.cppk2_convert_script(data, script, unknown_code, out, err))


def version() -> str:
    """The native library's package version (not this module's)."""
    return _library.cppk2_version().decode("utf-8")


def code_text(code: int) -> str:
    """The library's wording for a status code -- the only place that wording lives."""
    return _library.cppk2_code_text(int(code)).decode("utf-8")
